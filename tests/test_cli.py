"""The verbs, end to end, through the command line a reader actually types."""

from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path

import pytest
import yaml

from tests.helpers import add_dynamics, build


def run(*args: str) -> subprocess.CompletedProcess:
    return subprocess.run(
        [sys.executable, "-m", "otkd.cli.main", *args], capture_output=True, text=True
    )


def test_check_reports_the_rank_and_the_mobility(tmp_path):
    root = build(tmp_path, "double-wishbone")
    result = run("check", str(root))
    assert result.returncode == 0, result.stderr
    assert "mobility      1" in result.stdout
    assert "redundancy 0" in result.stdout


def test_check_fails_with_a_named_fault(tmp_path):
    root = build(tmp_path, "double-wishbone")
    topology = (root / "topology.yaml").read_text().replace("kind: revolute", "kind: magic", 1)
    (root / "topology.yaml").write_text(topology)
    result = run("check", str(root))
    assert result.returncode == 1
    assert "unknown kind 'magic'" in result.stderr


def test_solve_writes_the_payload(tmp_path):
    root = build(tmp_path, "double-wishbone")
    target = tmp_path / "out.json"
    result = run("solve", str(root), "--json", str(target), "--quiet")
    assert result.returncode == 0, result.stderr
    payload = json.loads(target.read_text())
    assert payload["meta"]["frames"] == len(payload["sweep"]["frames"]) == 9
    assert payload["meta"]["travel"]["unit"] == "rad"


def test_emit_writes_an_es_module(tmp_path):
    root = build(tmp_path, "double-wishbone")
    target = tmp_path / "out.js"
    result = run("emit", str(root), str(target), "--quiet")
    assert result.returncode == 0, result.stderr
    text = target.read_text()
    assert text.startswith("// Generated by otkd")
    assert "export const meta = " in text
    assert "import " not in text


def test_kinds_lists_the_library(tmp_path):
    root = build(tmp_path, "double-wishbone")
    result = run("kinds", str(root))
    assert result.returncode == 0, result.stderr
    assert "spherical" in result.stdout
    assert "tx=locked" in result.stdout


def test_compile_latex_uses_readable_names(tmp_path):
    root = build(tmp_path, "double-wishbone")
    result = run("compile", str(root), "--format", "latex")
    assert result.returncode == 0, result.stderr
    assert r"P_{\text{lcaf},x}" in result.stdout
    assert "g_{" not in result.stdout


def test_emit_wasm_refuses_a_model_it_cannot_solve(tmp_path):
    root = build(tmp_path, "double-wishbone")
    topology = (root / "topology.yaml").read_text()
    (root / "topology.yaml").write_text(topology.split("actuators:")[0])
    result = run("emit", str(root), str(tmp_path / "kernel"), "--format", "wasm", "--quiet")
    assert result.returncode == 1
    assert "under-determined" in result.stderr
    assert "Traceback" not in result.stderr


def test_solve_a_dynamics_study(tmp_path):
    root = build(tmp_path, "double-wishbone-compliant")
    add_dynamics(root)
    study = {
        "analysis": "dynamics",
        "duration": 0.05,
        "steps": 21,
        "loads": [{"site": "wc", "force": [1800.0, 0.0, -3500.0]}],
    }
    (root / "study.yaml").write_text(yaml.safe_dump(study, sort_keys=False))

    result = run("solve", str(root))
    assert result.returncode == 0, result.stderr
    assert "energy" in result.stdout

    target = tmp_path / "trajectory.json"
    written = run("solve", str(root), "--json", str(target), "--quiet")
    assert written.returncode == 0, written.stderr
    payload = json.loads(target.read_text())
    assert payload["meta"]["analysis"] == "dynamics"
    assert len(payload["trajectory"]) == 21

    refused = run("emit", str(root), str(tmp_path / "out.js"), "--quiet")
    assert refused.returncode == 1
    assert "trajectory" in refused.stderr
